// Extracts, verbatim, the Annex of Commission Implementing Decision
// (EU) 2018/1523 (model accessibility statement under Directive (EU)
// 2016/2102) in every official language in which EUR-Lex publishes it.
// Italic runs are kept, because the model marks text to replace in italics.
// Usage: node scripts/legal/extract-model-statement.mjs <sources-dir> <out.ts>
import { createHash } from 'node:crypto';
import { access, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { htmlToBlocks, blockText } from './html-blocks.mjs';
import { EU_LANGUAGES, SOURCES } from './sources.mjs';

const [srcDir, outFile] = process.argv.slice(2);
if (!srcDir || !outFile) {
  console.error('Usage: node scripts/legal/extract-model-statement.mjs <sources-dir> <out.ts>');
  process.exit(2);
}
const RETRIEVED = process.env.RETRIEVED ?? new Date().toISOString().slice(0, 10);

const EXPECTED_BLOCKS = 77; // 75 annex blocks + 2 footnotes, identical in every language
const KEEP = 75; // footnotes are dropped: the model says endnotes are deleted before publication
const LABELS = [12, 14, 16, 20, 23, 26];
const LABEL_RE = /^\(?[\p{L}\d]{1,5}[.)]$/u;

const result = {};
const missing = [];
for (const lang of EU_LANGUAGES) {
  const file = join(srcDir, 'd1523', `${lang}.html`);
  try {
    await access(file);
  } catch {
    missing.push(lang);
    continue;
  }
  const html = await readFile(file, 'utf8');
  const sha256 = createHash('sha256').update(html).digest('hex');
  const blocks = htmlToBlocks(html);
  const docTi = blocks.map((b, i) => [b, i]).filter(([b]) => b.cls === 'oj-doc-ti').map(([, i]) => i);
  const start = docTi.at(-1);
  if (start === undefined) throw new Error(`${lang}: no annex`);
  const annex = blocks.slice(start);
  if (annex.length !== EXPECTED_BLOCKS) throw new Error(`${lang}: expected ${EXPECTED_BLOCKS} blocks, got ${annex.length}`);
  for (const i of LABELS) {
    const t = blockText(annex[i]).trim();
    if (!LABEL_RE.test(t)) throw new Error(`${lang}: label check failed at ${i}: ${t}`);
  }
  // Title of the decision: first three title blocks.
  const title = [blockText(blocks[docTi[0]]), blockText(blocks[docTi[1]]), blockText(blocks[docTi[2]])].map((t) => t.trim());
  result[lang.toLowerCase()] = {
    source: 'official',
    url: SOURCES.modelStatement.url(lang),
    sha256,
    title,
    blocks: annex.slice(0, KEEP).map((b) => b.segments.map((s) => (s.italic ? { t: s.text, i: true } : { t: s.text }))),
  };
  console.log(`${lang}: ok`);
}

const banner = `// Copyright 2026 MB AFKzona Group
// SPDX-License-Identifier: AGPL-3.0-only
//
// GENERATED by scripts/legal/extract-model-statement.mjs. Do not edit by hand.
// Verbatim Annex of Commission Implementing Decision (EU) 2018/1523
// (CELEX ${SOURCES.modelStatement.celex}), ${SOURCES.modelStatement.eli},
// taken from EUR-Lex on ${RETRIEVED}. "i: true" marks italic text, which the
// model says the public sector body deletes or changes.
// Languages without an official text on EUR-Lex: ${missing.join(', ') || 'none'}.
import type { ModelStatementData } from './model-statement-types.js';

export const MODEL_STATEMENT_RETRIEVED = ${JSON.stringify(RETRIEVED)};
export const MODEL_STATEMENT_CELEX = ${JSON.stringify(SOURCES.modelStatement.celex)};
export const MODEL_STATEMENT_ELI = ${JSON.stringify(SOURCES.modelStatement.eli)};
export const MODEL_STATEMENT_MISSING_LANGUAGES: readonly string[] = ${JSON.stringify(missing.map((l) => l.toLowerCase()))};

export const MODEL_STATEMENT: ModelStatementData = ${JSON.stringify(result)};
`;
await writeFile(outFile, banner, 'utf8');
