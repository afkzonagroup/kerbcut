// Writes src/data/axe-rules.generated.ts from the installed axe-core rule
// metadata. Run after upgrading axe-core:
//   node scripts/generate-axe-mapping.mjs
// test/mapping.test.ts fails when this file is out of date.
import { createRequire } from 'node:module';
import { writeFile } from 'node:fs/promises';

const require = createRequire(import.meta.url);
const axe = require('axe-core');
const { version } = require('axe-core/package.json');

/** "wcag1412" -> "1.4.12" */
export function wcagTagToSc(tag) {
  const m = /^wcag(\d)(\d)(\d{1,2})$/.exec(tag);
  return m ? `${m[1]}.${m[2]}.${m[3]}` : undefined;
}

const LEVEL_TAGS = ['wcag2a', 'wcag2aa', 'wcag2aaa', 'wcag21a', 'wcag21aa', 'wcag21aaa', 'wcag22a', 'wcag22aa', 'wcag22aaa'];

const rules = axe
  .getRules()
  .map((r) => ({
    id: r.ruleId,
    sc: r.tags.map(wcagTagToSc).filter((x) => x !== undefined).sort(),
    levelTags: r.tags.filter((t) => LEVEL_TAGS.includes(t)).sort(),
    axeEnTags: r.tags.filter((t) => /^EN-9\./.test(t)).map((t) => t.slice(3)).sort(),
    experimental: r.tags.includes('experimental'),
    deprecated: r.tags.includes('deprecated'),
    bestPractice: r.tags.includes('best-practice'),
  }))
  .sort((a, b) => a.id.localeCompare(b.id));

const out = `// Copyright 2026 MB AFKzona Group
// SPDX-License-Identifier: AGPL-3.0-only
//
// GENERATED by scripts/generate-axe-mapping.mjs from axe-core ${version}.
// Do not edit by hand. "sc" lists the WCAG success criteria that axe-core
// tags each rule with; "axeEnTags" are axe-core's own EN 301 549 tags, kept
// only to cross-check this project's mapping in tests.
import type { AxeRuleMeta } from './axe-rules-types.js';

export const AXE_RULES_VERSION = ${JSON.stringify(version)};

export const AXE_RULES: readonly AxeRuleMeta[] = ${JSON.stringify(rules, null, 2)};
`;
await writeFile(new URL('../src/data/axe-rules.generated.ts', import.meta.url), out, 'utf8');
console.log(`wrote ${rules.length} rules from axe-core ${version}`);
